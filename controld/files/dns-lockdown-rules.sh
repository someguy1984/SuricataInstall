#!/bin/bash
# Print the Suricata rules for the DNS lockdown, built from doh-resolvers.conf.
# The output is installed as /etc/suricata/dns-lockdown.rules by controld/install.sh, and by
# the Suricata install.sh when the lockdown is already in place. Nothing runs this at runtime.
#
# Usage: dns-lockdown-rules.sh [LIST]   rules for the hostnames in LIST (default: doh-resolvers.conf here)
#        dns-lockdown-rules.sh --stub   the placeholder used while the lockdown isn't installed
#
# These rules belong to the lockdown rather than to Suricata's own local.rules because they
# drop every plain DNS packet leaving the machine: without ctrld answering on 127.0.0.1 that
# is all of this machine's DNS.
set -euo pipefail

if [[ ${1:-} == --stub ]]; then
    cat <<'EOF'
# Placeholder: the Control D DNS lockdown (controld/install.sh) is not installed, so nothing
# here stops DNS leaving this machine. controld/install.sh replaces this file with the rules.
EOF
    exit 0
fi

LIST=${1:-$(dirname "$(readlink -f "$0")")/doh-resolvers.conf}
[[ -r $LIST ]] || { echo "Cannot read $LIST" >&2; exit 1; }

cat <<'EOF'
# Generated by controld/files/dns-lockdown-rules.sh from doh-resolvers.conf. Don't edit this
# copy: change the list and re-run controld/install.sh. SIDs 9000000-9099999 are local.

# No unencrypted DNS may leave this machine: ctrld resolves everything over DoH (443).
# These drop the fallback that ctrld uses when its upstream fails (leak_on_upstream_failure),
# which the DNSLOCK firewall chain lets through because it exempts ctrld's cgroup.
# Loopback (ctrld itself) never reaches NFQUEUE. HOME_NET includes the guests of any bridge
# this machine routes for, so a VM or container with a hard-coded resolver is covered too,
# while guests asking this machine's own bridge address (HOME_NET to HOME_NET) are not affected.
drop udp $HOME_NET any -> $EXTERNAL_NET 53 (msg:"LOCAL Plain DNS (UDP) leaving this machine"; classtype:policy-violation; sid:9000001; rev:1;)
drop tcp $HOME_NET any -> $EXTERNAL_NET 53 (msg:"LOCAL Plain DNS (TCP) leaving this machine"; classtype:policy-violation; sid:9000002; rev:1;)
drop tcp $HOME_NET any -> $EXTERNAL_NET 853 (msg:"LOCAL DNS-over-TLS leaving this machine (not ctrld)"; classtype:policy-violation; sid:9000003; rev:1;)
drop udp $HOME_NET any -> $EXTERNAL_NET 853 (msg:"LOCAL DNS-over-QUIC leaving this machine (not ctrld)"; classtype:policy-violation; sid:9000004; rev:1;)

# DoH bypass: apps that bring their own DNS-over-HTTPS resolver skip ctrld (and so the Control D
# profile) entirely, over ordinary port 443. Drop TLS (DoH) and QUIC (DoH3) connections whose SNI
# is a well-known public resolver; subdomains match too (dotprefix), e.g. mozilla.cloudflare-dns.com.
# The DNSLOCK firewall chain also rejects 443 to these resolvers' fixed IPs, which covers
# connections that hide their SNI (ECH).
EOF

n=0
while read -r host; do
    [[ $host =~ ^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$ ]] || { echo "Not a hostname in $LIST: $host" >&2; exit 1; }
    n=$((n + 1))
    # 9000101-9000199 are the TLS rules, 9000201-9000299 the QUIC ones
    [[ $n -le 99 ]] || { echo "More than 99 hostnames in $LIST: the SID ranges need widening" >&2; exit 1; }
    printf 'drop tls $HOME_NET any -> $EXTERNAL_NET any (msg:"LOCAL DoH bypass to public resolver %s"; tls.sni; dotprefix; content:".%s"; endswith; nocase; classtype:policy-violation; sid:%d; rev:1;)\n' \
        "$host" "$host" $((9000100 + n))
    printf 'drop quic $HOME_NET any -> $EXTERNAL_NET any (msg:"LOCAL DoH3 bypass to public resolver %s"; quic.sni; dotprefix; content:".%s"; endswith; nocase; classtype:policy-violation; sid:%d; rev:1;)\n' \
        "$host" "$host" $((9000200 + n))
done < <(sed -e 's/#.*//' -e 's/[[:space:]]//g' "$LIST" | awk '/[A-Za-z]/ && !/:/')
[[ $n -gt 0 ]] || { echo "No hostnames found in $LIST" >&2; exit 1; }
